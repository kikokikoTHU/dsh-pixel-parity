/**
 * IR → Qt Quick (QML) generator.
 *
 * Two modes:
 * - absolute (default): every node is a positioned Rectangle; exact snapshot.
 * - semantic: containers whose children are sequential with a uniform gap become
 *   Row/Column; everything else falls back to absolute positioning per node.
 */

import { expandStyle } from './ir.mjs'

const WEIGHT_NAMES = {
  100: 'Font.Thin',
  200: 'Font.ExtraLight',
  300: 'Font.Light',
  400: 'Font.Normal',
  500: 'Font.Medium',
  600: 'Font.DemiBold',
  700: 'Font.Bold',
  800: 'Font.ExtraBold',
  900: 'Font.Black',
}

/**
 * Render an IR document as a QML component.
 * @param {object} ir - IR document.
 * @param {{semantic?: boolean}} [options] - semantic layout mapping.
 * @returns {string} QML source.
 */
export function generateQml(ir, options = {}) {
  const semantic = options.semantic === true
  const viewport = ir.source.viewport
  const rootStyle = expandStyle(ir.root.style, ir.tokens)
  const fonts = (ir.assets?.fonts ?? []).map((font, index) => {
    return `  FontLoader { id: irFont${index}; source: "${escapeQml(font.src)}" }`
  }).join('\n')
  const background = colorOf(rootStyle.backgroundColor) ?? 'transparent'
  const rootFlow = semantic ? flowInfo(ir.root) : undefined
  const body = rootFlow === undefined
    ? (ir.root.children ?? []).map(child => renderNode(child, ir.root, ir, 1, { kind: 'absolute' }, semantic)).join('\n')
    : renderRootFlow(ir, rootFlow, semantic)
  return `// Generated by dsh-pixel-parity from IR v1.${semantic ? ' Semantic layout mode.' : ' Static snapshot.'}
import QtQuick 2.14

Rectangle {
  id: irRoot
  width: ${number(viewport.width)}
  height: ${number(viewport.height)}
  color: "${background}"

${fonts}

${body}
}
`
}

function renderRootFlow(ir, flow, semantic) {
  const inner = flow.direction === 'row' ? 'Row' : 'Column'
  const children = flow.children.map((child) => {
    const offset = flow.direction === 'row'
      ? child.box.y - (ir.root.box.y + flow.padTop)
      : child.box.x - (ir.root.box.x + flow.padLeft)
    const placement = flow.direction === 'row'
      ? { kind: 'rowChild', offset }
      : { kind: 'columnChild', offset }
    return renderNode(child, ir.root, ir, 2, placement, semantic)
  })
  return `  ${inner} {
    ${flowAnchors(flow).join('\n    ')}
    spacing: ${number(flow.gap)}
${children.join('\n')}
  }`
}

function renderNode(node, parent, ir, depth, placement, semantic) {
  const style = expandStyle(node.style, ir.tokens)
  if (semantic && node.tag === 'table') {
    const table = tableLayout(node)
    if (table !== undefined) return renderTable(node, parent, ir, depth, placement, table, semantic)
  }
  const flow = semantic ? flowInfo(node) : undefined
  if (flow !== undefined) return renderFlow(node, parent, ir, depth, placement, flow, semantic)
  return renderAbsolute(node, parent, ir, depth, placement, style, semantic)
}

function placementProps(node, parent, placement) {
  const width = number(placement.width ?? node.box.w)
  const height = number(node.box.h)
  if (placement.kind === 'rowChild') {
    return [`width: ${width}`, `height: ${height}`, `y: ${number(placement.offset)}`]
  }
  if (placement.kind === 'columnChild') {
    return [`width: ${width}`, `height: ${height}`, `x: ${number(placement.offset)}`]
  }
  return [
    `x: ${number(node.box.x - parent.box.x)}`,
    `y: ${number(node.box.y - parent.box.y)}`,
    `width: ${width}`,
    `height: ${height}`,
  ]
}

function paintProps(node, style) {
  const properties = []
  const background = colorOf(style.backgroundColor)
  properties.push(`color: "${background ?? 'transparent'}"`)
  const borderWidth = Number.parseFloat(style.borderTopWidth ?? '0')
  if (borderWidth > 0) {
    properties.push(`border.width: ${number(borderWidth)}`)
    properties.push(`border.color: "${colorOf(style.borderTopColor) ?? '#000000'}"`)
  }
  const radius = Number.parseFloat(style.borderRadius ?? '0')
  if (radius > 0) properties.push(`radius: ${number(radius)}`)
  const gradient = gradientProperty(style.backgroundImage)
  if (gradient !== undefined) properties.push(gradient)
  if (node.box.w === 0 || node.box.h === 0) properties.push('visible: false')
  return properties
}

/**
 * Map a vertical/horizontal CSS linear-gradient to QML `Gradient`.
 * Diagonal gradients fall back to a solid mid-stop color.
 */
function gradientProperty(value) {
  if (typeof value !== 'string' || !value.startsWith('linear-gradient')) return undefined
  const inner = value.slice(value.indexOf('(') + 1, value.lastIndexOf(')'))
  const parts = splitTopLevel(inner)
  let horizontal = false
  let reverse = false
  let index = 0
  const head = (parts[0] ?? '').trim()
  if (/^to\s+right/i.test(head) || /^90deg/i.test(head)) {
    horizontal = true
  } else if (/^to\s+left/i.test(head) || /^270deg/i.test(head)) {
    horizontal = true
    reverse = true
  } else if (/^to\s+top/i.test(head) || /^0deg/i.test(head)) {
    reverse = true
  } else if (/^to\s+bottom/i.test(head) || /^180deg/i.test(head)) {
    reverse = false
  } else if (/deg|^to\s+/i.test(head)) {
    return undefined
  } else {
    index = -1 // first part is already a color stop
  }

  const stops = []
  let cursor = index + 1
  for (; cursor < parts.length; cursor += 1) {
    const stop = parseColorStop(parts[cursor])
    if (stop !== undefined) stops.push(stop)
  }
  if (stops.length < 2) return undefined
  if (stops.some(stop => stop.position === undefined)) {
    stops.forEach((stop, stopIndex) => {
      stop.position = stops.length === 1 ? 0 : stopIndex / (stops.length - 1)
    })
  }
  stops.sort((left, right) => left.position - right.position)
  if (reverse) stops.reverse()
  const lines = stops.map(stop => `GradientStop { position: ${number(stop.position)}; color: "${stop.color}" }`)
  const orientationLine = horizontal ? '\n    orientation: Gradient.Horizontal' : ''
  return `gradient: Gradient {${orientationLine}\n${lines.map(line => `    ${line}`).join('\n')}\n  }`
}

function splitTopLevel(value) {
  const parts = []
  let depth = 0
  let current = ''
  for (const character of value) {
    if (character === '(') depth += 1
    if (character === ')') depth -= 1
    if (character === ',' && depth === 0) {
      parts.push(current)
      current = ''
      continue
    }
    current += character
  }
  parts.push(current)
  return parts
}

function parseColorStop(value) {
  const text = value.trim()
  if (text.length === 0) return undefined
  const functionColor = /^(rgba?\([^)]*\))/i.exec(text)
  const hexColor = /^(#[0-9a-f]{3,8})/i.exec(text)
  const color = functionColor?.[1] ?? hexColor?.[1]
  if (color === undefined) return undefined
  const rest = text.slice(color.length).trim()
  const position = /^(\d+(?:\.\d+)?)%/.exec(rest)
  return {
    color: colorOf(color) ?? color,
    position: position === null ? undefined : Number(position[1]) / 100,
  }
}

function backgroundImageChild(style, indent) {
  const value = style.backgroundImage
  if (typeof value !== 'string' || !value.includes('url(')) return ''
  const match = /url\((['"]?)([^'")]+)\1\)/.exec(value)
  if (match === null) return ''
  const fill = style.backgroundSize === 'contain'
    ? 'Image.PreserveAspectFit'
    : style.backgroundSize === 'cover'
      ? 'Image.PreserveAspectCrop'
      : 'Image.Stretch'
  return `${indent}Image {
${indent}  anchors.fill: parent
${indent}  source: "${escapeQml(imageSource(match[2]))}"
${indent}  fillMode: ${fill}
${indent}  z: -1
${indent}}`
}

function renderAbsolute(node, parent, ir, depth, placement, style, semantic) {
  const indent = '  '.repeat(depth)
  let base = placementProps(node, parent, placement)
  const rotation = rotationOf(style)
  if (rotation !== undefined && node.transformedSize !== undefined) {
    const layoutWidth = Number.parseFloat(node.transformedSize.width)
    const layoutHeight = Number.parseFloat(node.transformedSize.height)
    if (Number.isFinite(layoutWidth) && Number.isFinite(layoutHeight)) {
      if (placement.kind === 'absolute') {
        base = [
          `x: ${number(node.box.x + node.box.w / 2 - layoutWidth / 2)}`,
          `y: ${number(node.box.y + node.box.h / 2 - layoutHeight / 2)}`,
          `width: ${number(layoutWidth)}`,
          `height: ${number(layoutHeight)}`,
        ]
      } else {
        base = [`width: ${number(layoutWidth)}`, `height: ${number(layoutHeight)}`, base[base.length - 1]]
      }
      base.push(`rotation: ${number(rotation)}`, 'transformOrigin: Item.Center')
    }
  }
  if (node.tag === 'svg') {
    return `${indent}Image {
${indent}  ${base.join(`\n${indent}  `)}
${indent}  source: "${svgDataUri(node, ir)}"
${indent}  fillMode: Image.Stretch
${indent}}`
  }
  const mediaSource = node.tag === 'video' ? node.attributes?.poster : node.attributes?.src
  if ((node.tag === 'img' || node.tag === 'canvas' || node.tag === 'video') && mediaSource !== undefined) {
    return `${indent}Image {
${indent}  ${base.join(`\n${indent}  `)}
${indent}  source: "${escapeQml(imageSource(mediaSource))}"
${indent}  fillMode: Image.Stretch
${indent}}`
  }
  const properties = [...base, ...paintProps(node, style)]
  const runs = (node.textRuns ?? []).map(run => renderText(run, node, style, depth + 1))
  const children = (node.children ?? []).map(child => renderNode(child, node, ir, depth + 1, { kind: 'absolute' }, semantic))
  const background = backgroundImageChild(style, depth + 1)
  if (background !== '') children.unshift(background)
  if (runs.length === 0 && children.length === 0) {
    return `${indent}Rectangle { ${properties.join('; ')} }`
  }
  return `${indent}Rectangle {
${indent}  ${properties.join(`\n${indent}  `)}
${children.join('\n')}
${runs.join('\n')}
${indent}}`
}

function renderFlow(node, parent, ir, depth, placement, flow, semantic) {
  const indent = '  '.repeat(depth)
  const style = expandStyle(node.style, ir.tokens)
  const properties = [...placementProps(node, parent, placement), ...paintProps(node, style)]
  const inner = flow.direction === 'row' ? 'Row' : 'Column'
  const anchors = flowAnchors(flow).join(`\n${indent}    `)
  const children = flow.children.map((child) => {
    const offset = flow.direction === 'row'
      ? child.box.y - (node.box.y + flow.padTop)
      : child.box.x - (node.box.x + flow.padLeft)
    const childPlacement = flow.direction === 'row'
      ? { kind: 'rowChild', offset }
      : { kind: 'columnChild', offset }
    return renderNode(child, node, ir, depth + 2, childPlacement, semantic)
  })
  const background = backgroundImageChild(style, indent + '  ')
  return `${indent}Rectangle {
${indent}  ${properties.join(`\n${indent}  `)}
${background === '' ? '' : `${background}\n`}${indent}  ${inner} {
${indent}    ${anchors}
${indent}    spacing: ${number(flow.gap)}
${children.join('\n')}
${indent}  }
${indent}}`
}

function flowAnchors(flow) {
  if (flow.direction === 'row') {
    if (flow.justify === 'center') return ['anchors.horizontalCenter: parent.horizontalCenter', `y: ${number(flow.padTop)}`]
    if (flow.justify === 'end') {
      return ['anchors.right: parent.right', `anchors.rightMargin: ${number(flow.padRight)}`, `y: ${number(flow.padTop)}`]
    }
    return [`x: ${number(flow.padLeft)}`, `y: ${number(flow.padTop)}`]
  }
  if (flow.justify === 'center') return ['anchors.verticalCenter: parent.verticalCenter', `x: ${number(flow.padLeft)}`]
  if (flow.justify === 'end') {
    return ['anchors.bottom: parent.bottom', `anchors.bottomMargin: ${number(flow.padBottom)}`, `x: ${number(flow.padLeft)}`]
  }
  return [`x: ${number(flow.padLeft)}`, `y: ${number(flow.padTop)}`]
}

/**
 * Collect rows and verify that cells can be laid out with the captured column
 * widths. Returns undefined when the table must stay an absolute snapshot.
 */
function tableLayout(node) {
  const columns = node.layout?.columnWidths
  if (!Array.isArray(columns) || columns.length === 0) return undefined
  const rows = []
  const collect = (parent) => {
    for (const child of parent.children ?? []) {
      if (child.tag === 'tr') rows.push(child)
      else if (['thead', 'tbody', 'tfoot'].includes(child.tag)) collect(child)
    }
  }
  collect(node)
  if (rows.length === 0) return undefined

  for (const row of rows) {
    let index = 0
    for (const cell of row.children ?? []) {
      if (cell.tag !== 'td' && cell.tag !== 'th') continue
      const span = Math.max(1, cell.colSpan ?? 1)
      if (index + span > columns.length) return undefined
      index += span
    }
    if (index !== columns.length) return undefined
  }

  const first = rows[0]
  const offsetX = first.box.x - node.box.x
  const offsetY = first.box.y - node.box.y
  let rowGap
  for (let index = 1; index < rows.length; index += 1) {
    const gap = rows[index].box.y - (rows[index - 1].box.y + rows[index - 1].box.h)
    if (rowGap === undefined) rowGap = gap
    else if (Math.abs(rowGap - gap) > 1) return undefined
  }
  return {
    columns,
    rows,
    offsetX,
    offsetY,
    rowGap: Math.max(0, rowGap ?? 0),
    width: columns.reduce((total, width) => total + width, 0),
  }
}

function renderTable(node, parent, ir, depth, placement, table, semantic) {
  const indent = '  '.repeat(depth)
  const style = expandStyle(node.style, ir.tokens)
  const properties = [...placementProps(node, parent, placement), ...paintProps(node, style)]
  const rows = table.rows.map((row) => {
    const cells = []
    let index = 0
    for (const cell of row.children ?? []) {
      if (cell.tag !== 'td' && cell.tag !== 'th') continue
      const span = Math.max(1, cell.colSpan ?? 1)
      let width = 0
      for (let step = 0; step < span; step += 1) width += table.columns[index + step]
      cells.push(renderNode(cell, row, ir, depth + 4, {
        kind: 'rowChild',
        offset: cell.box.y - row.box.y,
        width,
      }, semantic))
      index += span
    }
    return `${indent}    Row {
${indent}      width: ${number(table.width)}
${indent}      height: ${number(row.box.h)}
${indent}      spacing: 0
${cells.join('\n')}
${indent}    }`
  })
  return `${indent}Rectangle {
${indent}  ${properties.join(`\n${indent}  `)}
${indent}  Column {
${indent}    x: ${number(table.offsetX)}
${indent}    y: ${number(table.offsetY)}
${indent}    spacing: ${number(table.rowGap)}
${rows.join('\n')}
${indent}  }
${indent}}`
}

/**
 * Decide whether a container's children can be expressed as Row/Column.
 * Requires: at least two children, in flow, start-aligned on the main axis, and
 * a uniform gap between consecutive boxes.
 */
function flowInfo(node) {
  const kind = node.layout?.kind
  if (kind !== 'flex' && kind !== 'block') return undefined
  if (['table', 'thead', 'tbody', 'tfoot', 'tr', 'td', 'th'].includes(node.tag)) return undefined
  if (kind === 'flex' && node.layout.wrap === 'wrap') return undefined
  const children = node.children ?? []
  if (children.length < 2) return undefined
  if (children.some(child => child.style?.position === 'absolute' || child.style?.position === 'fixed')) return undefined

  const direction = kind === 'flex'
    ? (node.layout.direction === 'column' ? 'column' : 'row')
    : 'column'
  const ordered = [...children].sort((left, right) => (direction === 'row'
    ? left.box.x - right.box.x
    : left.box.y - right.box.y))

  const padLeft = px(node.style.paddingLeft)
  const padTop = px(node.style.paddingTop)
  const padRight = px(node.style.paddingRight)
  const padBottom = px(node.style.paddingBottom)
  const contentStart = direction === 'row' ? node.box.x + padLeft : node.box.y + padTop
  const contentEnd = direction === 'row' ? node.box.x + node.box.w - padRight : node.box.y + node.box.h - padBottom
  const firstStart = direction === 'row' ? ordered[0].box.x : ordered[0].box.y

  const rawJustify = node.style.justifyContent ?? 'normal'
  let justify = 'start'
  if (rawJustify === 'center') justify = 'center'
  else if (rawJustify === 'flex-end' || rawJustify === 'end') justify = 'end'
  else if (rawJustify === 'space-between') {
    // Equal gaps from the first child: identical to start alignment when the
    // captured gap is already the distributed spacing.
    justify = 'start'
  } else if (!['normal', 'flex-start', 'start', 'stretch'].includes(rawJustify)) return undefined

  let gap
  for (let index = 1; index < ordered.length; index += 1) {
    const previous = ordered[index - 1]
    const current = ordered[index]
    const currentGap = direction === 'row'
      ? current.box.x - (previous.box.x + previous.box.w)
      : current.box.y - (previous.box.y + previous.box.h)
    if (gap === undefined) gap = currentGap
    else if (Math.abs(gap - currentGap) > 1) return undefined
  }
  if (gap === undefined || gap < -1) return undefined

  let total = 0
  ordered.forEach((child, index) => {
    total += direction === 'row' ? child.box.w : child.box.h
    if (index > 0) total += gap
  })
  const offset = justify === 'center'
    ? (contentEnd - contentStart - total) / 2
    : justify === 'end'
      ? contentEnd - contentStart - total
      : 0
  if (Math.abs(firstStart - (contentStart + offset)) > 1) return undefined

  return {
    direction,
    justify,
    gap: Math.max(0, gap),
    padLeft,
    padTop,
    padRight,
    padBottom,
    children: ordered,
  }
}

function px(value) {
  const parsed = Number.parseFloat(value ?? '0')
  return Number.isFinite(parsed) ? parsed : 0
}

/** Extract a pure-rotation angle (degrees) from a CSS matrix, or undefined. */
function rotationOf(style) {
  const value = style.transform
  if (typeof value !== 'string' || !value.startsWith('matrix(')) return undefined
  const numbers = value.slice('matrix('.length, -1).split(',').map(part => Number(part.trim()))
  if (numbers.length !== 6 || numbers.some(part => !Number.isFinite(part))) return undefined
  const [a, b, c, d] = numbers
  if (Math.abs(a - d) > 0.001 || Math.abs(b + c) > 0.001) return undefined
  const scale = Math.hypot(a, b)
  if (Math.abs(scale - 1) > 0.001) return undefined
  return Math.round((Math.atan2(b, a) * 180 / Math.PI) * 10) / 10
}

function renderText(run, node, style, depth) {
  const indent = '  '.repeat(depth)
  const properties = [
    `x: ${number(run.box.x - node.box.x)}`,
    `y: ${number(run.box.y - node.box.y)}`,
    `width: ${number(run.box.w)}`,
    `height: ${number(run.box.h)}`,
    `text: "${escapeQml(run.text)}"`,
    `color: "${colorOf(style.color) ?? '#000000'}"`,
    `font.pixelSize: ${Math.max(1, Math.round(Number.parseFloat(style.fontSize ?? '14'))) || 14}`,
    `font.weight: ${WEIGHT_NAMES[Math.round(Number(style.fontWeight ?? 400))] ?? 'Font.Normal'}`,
    'wrapMode: Text.NoWrap',
  ]
  const family = firstFamily(style.fontFamily)
  if (family !== undefined) properties.push(`font.family: "${escapeQml(family)}"`)
  const spacing = Number.parseFloat(style.letterSpacing ?? '0')
  if (Number.isFinite(spacing) && spacing !== 0) properties.push(`font.letterSpacing: ${number(spacing)}`)
  return `${indent}Text { ${properties.join('; ')} }`
}

function firstFamily(fontFamily) {
  if (typeof fontFamily !== 'string' || fontFamily.length === 0) return undefined
  return fontFamily.split(',')[0].replace(/["']/g, '').trim()
}

function colorOf(value) {
  if (typeof value !== 'string' || value.length === 0) return undefined
  const trimmed = value.trim()
  if (trimmed === 'transparent' || trimmed === 'rgba(0, 0, 0, 0)') return 'transparent'
  const match = /^rgba?\(([^)]+)\)$/.exec(trimmed)
  if (match === null) return trimmed
  const parts = match[1].split(/[,\s/]+/).filter(Boolean).map(Number)
  const [red, green, blue, alpha = 1] = parts
  if ([red, green, blue].some(part => !Number.isFinite(part))) return undefined
  const hex = `#${[red, green, blue].map(part => Math.round(part).toString(16).padStart(2, '0')).join('')}`
  if (alpha >= 0.995) return hex
  return `#${Math.round(alpha * 255).toString(16).padStart(2, '0')}${hex.slice(1)}`
}

function imageSource(source) {
  if (/^(file:|https?:|data:)/i.test(source)) return source
  if (/^[a-zA-Z]:[\\/]/.test(source)) return `file:///${source.replaceAll('\\', '/')}`
  return source
}

const SVG_SHAPES = new Set(['circle', 'ellipse', 'rect', 'line', 'polyline', 'polygon', 'path', 'g'])

/** Serialize an inline SVG subtree into a data URI the QML Image can load. */
function svgDataUri(node, ir) {
  const attributes = node.attributes ?? {}
  const viewBox = attributes.viewBox ?? `0 0 ${node.box.w} ${node.box.h}`
  const width = attributes.width ?? node.box.w
  const height = attributes.height ?? node.box.h
  const shapes = (node.children ?? []).map(child => svgShape(child, ir)).join('')
  const source = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${xml(viewBox)}" width="${xml(width)}" height="${xml(height)}">${shapes}</svg>`
  return `data:image/svg+xml;base64,${Buffer.from(source, 'utf8').toString('base64')}`
}

function svgShape(node, ir) {
  if (!SVG_SHAPES.has(node.tag)) return ''
  const attributes = Object.entries(node.attributes ?? {})
    .map(([key, value]) => `${key}="${xml(value)}"`)
    .join(' ')
  const style = expandStyle(node.style ?? {}, ir.tokens)
  const paint = []
  const fill = svgColor(style.fill)
  if (fill !== undefined) {
    paint.push(`fill="${fill.color}"`)
    if (fill.opacity !== undefined) paint.push(`fill-opacity="${fill.opacity}"`)
  }
  const stroke = svgColor(style.stroke)
  if (stroke !== undefined && stroke.color !== 'none') {
    paint.push(`stroke="${stroke.color}"`)
    if (stroke.opacity !== undefined) paint.push(`stroke-opacity="${stroke.opacity}"`)
  }
  if (style.strokeWidth !== undefined) paint.push(`stroke-width="${xml(style.strokeWidth)}"`)
  if (style.strokeLinecap !== undefined) paint.push(`stroke-linecap="${xml(style.strokeLinecap)}"`)
  if (style.strokeLinejoin !== undefined) paint.push(`stroke-linejoin="${xml(style.strokeLinejoin)}"`)
  if (style.strokeDasharray !== undefined && style.strokeDasharray !== 'none') {
    paint.push(`stroke-dasharray="${xml(style.strokeDasharray)}"`)
  }
  const children = (node.children ?? []).map(child => svgShape(child, ir)).join('')
  return `<${node.tag} ${attributes} ${paint.join(' ')}>${children}</${node.tag}>`
}

function svgColor(value) {
  if (typeof value !== 'string' || value === '' || value === 'none') return undefined
  const color = colorOf(value)
  if (color === undefined) return { color: value }
  if (color.startsWith('#') && color.length === 9) {
    const alpha = Number.parseInt(color.slice(1, 3), 16) / 255
    return { color: `#${color.slice(3)}`, opacity: Math.round(alpha * 1000) / 1000 }
  }
  return { color }
}

function xml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
}

function number(value) {
  if (!Number.isFinite(value)) return '0'
  return String(Math.round(value * 10) / 10)
}

function escapeQml(value) {
  return String(value)
    .replaceAll('\\', '\\\\')
    .replaceAll('"', '\\"')
    .replaceAll('\n', '\\n')
}
